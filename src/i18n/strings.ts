// "15 min", "1 h 40 min" o "2 h" (redondeado a 5 minutos cuando pasa de una hora).
function hoursMinutes(minutes: number) {
  if (minutes < 60) return `${Math.round(minutes)} min`;
  const total = Math.round(minutes / 5) * 5;
  const rest = total % 60;
  return `${Math.floor(total / 60)} h${rest ? ` ${rest} min` : ""}`;
}

